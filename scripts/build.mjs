#!/usr/bin/env node
// Bundles every component module into components/bundle.js, one request instead of ~700. Each module
// keeps its own function scope (files reuse top-level names), `export default` becomes the scope's return
// value, and a hash of all sources is embedded so `npm run validate` can tell when the bundle is stale.
// The per-file sources stay the editable truth and are what the page loads on localhost.
// Usage: node scripts/build.mjs [--check]   (--check: exit 1 if the committed bundle is stale)
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'components');
const OUT = join(ROOT, 'bundle.js');
const { CATEGORIES } = await import(join(ROOT, 'manifest.js'));

// Resolve a category's component files in the order its index.js exports them.
async function filesOf(cat) {
  const idx = await readFile(join(ROOT, cat, 'index.js'), 'utf8');
  const imports = new Map([...idx.matchAll(/import\s+(\w+)\s+from\s+['"]\.\/([^'"]+)['"]/g)].map((m) => [m[1], m[2]]));
  const list = idx.match(/export\s+default\s*\[([\s\S]*?)\]/);
  const names = list ? list[1].split(',').map((s) => s.trim()).filter(Boolean) : [...imports.keys()];
  return names.map((n) => { if (!imports.has(n)) throw new Error(`${cat}/index.js exports unknown name ${n}`); return imports.get(n); });
}

export async function sourceHash() {
  const h = createHash('sha256');
  for (const cat of CATEGORIES) {
    const files = (await readdir(join(ROOT, cat))).filter((f) => f.endsWith('.js')).sort();
    for (const f of files) { h.update(`${cat}/${f}\n`); h.update(await readFile(join(ROOT, cat, f))); }
  }
  return h.digest('hex').slice(0, 16);
}

function wrap(cat, file, src) {
  const n = (src.match(/^export default\b/gm) || []).length;
  if (n !== 1) throw new Error(`${cat}/${file}: expected exactly one top-level "export default", found ${n}`);
  if (/^\s*import\s/m.test(src) || /import\.meta/.test(src)) throw new Error(`${cat}/${file}: imports are not allowed in components`);
  const body = src.replace(/^export default\b/m, 'const __def =');
  return `// components/${cat}/${file}\n(() => {\n${body.trimEnd()}\nreturn __def;\n})()`;
}

export async function build() {
  const hash = await sourceHash();
  const groups = [];
  let count = 0;
  for (const cat of CATEGORIES) {
    const parts = [];
    for (const f of await filesOf(cat)) { parts.push(wrap(cat, f, await readFile(join(ROOT, cat, f), 'utf8'))); count++; }
    groups.push(`{ cat: ${JSON.stringify(cat)}, list: [\n${parts.join(',\n')}\n] }`);
  }
  const out = `// GENERATED by scripts/build.mjs — do not edit; edit components/<category>/*.js and run \`npm run build\`.\n` +
    `export const HASH = ${JSON.stringify(hash)};\nexport default [\n${groups.join(',\n')}\n];\n`;
  return { out, hash, count };
}

export async function bundleHash() {
  try { const m = (await readFile(OUT, 'utf8')).match(/^export const HASH = "([0-9a-f]+)";/m); return m ? m[1] : null; } catch { return null; }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const [a, b] = [await sourceHash(), await bundleHash()];
    if (a !== b) { console.error(`components/bundle.js is ${b ? 'stale' : 'missing'} (sources ${a}, bundle ${b}); run: npm run build`); process.exit(1); }
    console.log(`components/bundle.js is up to date (${a})`);
  } else {
    const { out, hash, count } = await build();
    await writeFile(OUT, out);
    console.log(`wrote components/bundle.js: ${count} components, ${(out.length / 1024).toFixed(0)} KB, sources ${hash}`);
  }
}
